def area(a, h):
    '''Принимает основание a и высоту h, возвращает площадь треугольника.
    Пример вызова: triangle.area(6, 4) -> 12.0
    '''
    return a * h / 2


def perimeter(a, b, c):
    '''Принимает стороны a, b и c, возвращает периметр треугольника.
    Пример вызова: triangle.perimeter(3, 4, 5) -> 12
    '''
    return a + b + c
