def area(a, b):
    '''Принимает стороны a и b, возвращает площадь прямоугольника.
    Пример вызова: rectangle.area(3, 4) -> 12
    '''
    return a * b


def perimeter(a, b):
    '''Принимает стороны a и b, возвращает периметр прямоугольника.
    Пример вызова: rectangle.perimeter(3, 4) -> 14
    '''
    return (a + b) * 2
